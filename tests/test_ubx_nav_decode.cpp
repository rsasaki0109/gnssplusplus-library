TEST(UBXNavDecodeTest, GpsKlobucharPage18) {
    io::UBXNavDecoder decoder;
    EXPECT_FALSE(decoder.hasKlobuchar());
    std::vector<Ephemeris> out;
    decoder.pushSfrbx(toSfrbx(kG02Subframe4Page18), out);
    ASSERT_TRUE(decoder.hasKlobuchar());
    const auto& model = decoder.klobuchar();
    EXPECT_TRUE(model.valid);
    // alpha 2^-30, 2^-27, 2^-24, 2^-24; beta 2^11, 2^14, 2^16, 2^16 times the broadcast integers.
    EXPECT_DOUBLE_EQ(model.alpha[0], 33 * std::ldexp(1.0, -30));
    EXPECT_DOUBLE_EQ(model.alpha[1], 2 * std::ldexp(1.0, -27));
    EXPECT_DOUBLE_EQ(model.alpha[2], -2 * std::ldexp(1.0, -24));
    EXPECT_DOUBLE_EQ(model.alpha[3], -2 * std::ldexp(1.0, -24));
    EXPECT_DOUBLE_EQ(model.beta[0], 67 * std::ldexp(1.0, 11));
    EXPECT_DOUBLE_EQ(model.beta[1], 1 * std::ldexp(1.0, 14));
    EXPECT_DOUBLE_EQ(model.beta[2], -3 * std::ldexp(1.0, 16));
    EXPECT_DOUBLE_EQ(model.beta[3], 6 * std::ldexp(1.0, 16));
    EXPECT_EQ(decoder.stats().klobuchar_sets, 1U);
    // The same set to the RINEX print precision used by the BKG BRDC header (E12.4).
    EXPECT_NEAR(model.alpha[0], 3.0734e-8, 5e-13);  // BKG BRDC header GPSA, 2024/254
    EXPECT_NEAR(model.beta[3], 3.9322e5, 5.0);
    EXPECT_TRUE(out.empty());
}

