// Real UBX-RXM-SFRBX payload words (u-blox, JammerTest 2024-09-10 06:59-07:15 UTC,
// unattacked minutes) with the matching IGS BKG BRDC records (day 2024/254).
// Row: gnssId, svId, sigId, freqId, data words.
// ---------------------------------------------------------------------------
struct SfrbxRow {
    uint8_t gnss;
    uint8_t sv;
    uint8_t sig;
    uint8_t freq;
    std::vector<uint32_t> words;
};

io::UBXSfrbx toSfrbx(const SfrbxRow& row) {
    io::UBXSfrbx sfrbx;
    sfrbx.system = io::ubx_utils::getSystemFromGnssId(row.gnss);
    sfrbx.sv_id = row.sv;
    sfrbx.signal_id = row.sig;
    sfrbx.frequency_id = row.freq;
    sfrbx.words = row.words;
    return sfrbx;
}

