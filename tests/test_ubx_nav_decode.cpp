// Parse a RINEX 3 navigation record with the library's own reader.
Ephemeris readRinexRecord(const char* record) {
    const auto path = std::filesystem::temp_directory_path() / "libgnss_ubx_nav_decode_record.nav";
    {
        std::ofstream out(path);
        out << "     3.04           N: GNSS NAV DATA    M: MIXED            RINEX VERSION / TYPE\n"
            << "                                                            END OF HEADER\n"
            << record;
    }
    io::RINEXReader reader;
    EXPECT_TRUE(reader.open(path.string()));
    NavigationData nav;
    reader.readNavigationData(nav);
    reader.close();
    std::filesystem::remove(path);
    EXPECT_EQ(nav.ephemeris_data.size(), 1U);
    if (nav.ephemeris_data.empty()) {
        return Ephemeris();
    }
    return nav.ephemeris_data.begin()->second.front();
}

std::vector<Ephemeris> decodeRows(io::UBXNavDecoder& decoder, const std::vector<SfrbxRow>& rows) {
    std::vector<Ephemeris> out;
    for (const auto& row : rows) {
        decoder.pushSfrbx(toSfrbx(row), out);
    }
    return out;
}

void expectNear(double expected, double actual, const char* name, double rel = 1e-10) {
    const double tolerance = rel * std::max(std::abs(expected), 1e-6);
    EXPECT_NEAR(expected, actual, tolerance) << name;
}

// Everything the RINEX reader fills from a Kepler broadcast record.
void expectKeplerMatches(const Ephemeris& expected, const Ephemeris& actual) {
    EXPECT_EQ(expected.satellite.system, actual.satellite.system);
    EXPECT_EQ(expected.satellite.prn, actual.satellite.prn);
    EXPECT_EQ(expected.week, actual.week);
    EXPECT_NEAR(expected.toe - actual.toe, 0.0, 1e-6);
    EXPECT_NEAR(expected.toc - actual.toc, 0.0, 1e-6);
    EXPECT_EQ(expected.toes, actual.toes);
    EXPECT_EQ(expected.iode, actual.iode);
    EXPECT_EQ(expected.iodc, actual.iodc);
    EXPECT_EQ(expected.health, actual.health);
    EXPECT_EQ(expected.sv_health, actual.sv_health);
    EXPECT_EQ(expected.data_source_code, actual.data_source_code);
    expectNear(expected.af0, actual.af0, "af0");
    expectNear(expected.af1, actual.af1, "af1");
    expectNear(expected.af2, actual.af2, "af2");
    expectNear(expected.sqrt_a, actual.sqrt_a, "sqrt_a");
    expectNear(expected.e, actual.e, "e");
    expectNear(expected.i0, actual.i0, "i0");
    expectNear(expected.omega0, actual.omega0, "omega0");
    expectNear(expected.omega, actual.omega, "omega");
    expectNear(expected.m0, actual.m0, "m0");
    expectNear(expected.delta_n, actual.delta_n, "delta_n");
    expectNear(expected.omega_dot, actual.omega_dot, "omega_dot");
    expectNear(expected.idot, actual.idot, "idot");
    EXPECT_EQ(actual.idot, actual.i_dot);
    expectNear(expected.cuc, actual.cuc, "cuc");
    expectNear(expected.cus, actual.cus, "cus");
    expectNear(expected.crc, actual.crc, "crc");
    expectNear(expected.crs, actual.crs, "crs");
    expectNear(expected.cic, actual.cic, "cic");
    expectNear(expected.cis, actual.cis, "cis");
    expectNear(expected.tgd, actual.tgd, "tgd");
    expectNear(expected.tgd_secondary, actual.tgd_secondary, "tgd_secondary");
    EXPECT_TRUE(actual.valid);
}

