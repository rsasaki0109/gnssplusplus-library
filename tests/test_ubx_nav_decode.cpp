TEST(UBXNavDecodeTest, GpsLnavDropsInconsistentIodeAndNeedsReference) {
    // Subframe 1 of G21 (IODC 25) with subframes 2 and 3 of G24 (IODE 7), relabelled to one satellite.
    io::UBXNavDecoder decoder;
    decoder.setReferenceTime(kReference);
    std::vector<Ephemeris> out;
    auto mixed = kG21Iode25[0];
    decoder.pushSfrbx(toSfrbx(mixed), out);
    for (size_t i = 1; i < 3; ++i) {
        auto row = kG24Iode7[i];
        row.sv = 21;
        decoder.pushSfrbx(toSfrbx(row), out);
    }
    EXPECT_TRUE(out.empty());
    EXPECT_EQ(decoder.stats().systems.at(GNSSSystem::GPS).dropped.at("iode_mismatch"), 1U);

    // Without a time reference the 10-bit week cannot be resolved.
    io::UBXNavDecoder no_reference;
    EXPECT_TRUE(decodeRows(no_reference, kG21Iode25).empty());
    EXPECT_EQ(no_reference.stats().systems.at(GNSSSystem::GPS).dropped.at("no_time_reference"), 1U);
}

